"""
Reformat raw SKAB Valve1 runs into clean, human-readable CSV files.

Input : data/raw/skab/valve1/{0..15}.csv      (semicolon-delimited, SKAB original)
Output: data/processed/skab/valve1/
            run_00.csv ... run_15.csv          (one clean CSV per run)
            all_runs.csv                       (all runs stacked, with `run` column)
            run_index.csv                      (per-run summary / statistics)
            README.md                          (column dictionary)

Transformations applied
-----------------------
- delimiter `;` -> `,` (standard RFC 4180 CSV, UTF-8, LF newlines)
- headers -> snake_case, spaces removed
- `datetime` -> ISO format `YYYY-MM-DD HH:MM:SS`
- sensor values rounded to 4 decimals
- `anomaly` / `changepoint` -> integer flags (0/1)
- row order preserved; original timestamps never altered

Usage
-----
    python scripts/prepare_skab.py
    python scripts/prepare_skab.py --decimals 4 --out data/processed/skab/valve1
"""

import argparse
import os
import re
import sys

import pandas as pd

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DEFAULT_RAW_DIR = os.path.join(PROJECT_ROOT, "data", "raw", "skab", "valve1")
DEFAULT_OUT_DIR = os.path.join(PROJECT_ROOT, "data", "processed", "skab", "valve1")

# Flag columns stored as 0.0 / 1.0 in the raw files
FLAG_COLUMNS = ["anomaly", "changepoint"]

# Column name -> engineering unit (used for the generated README)
UNITS = {
    "accelerometer1_rms": "g (m/s^2)",
    "accelerometer2_rms": "g (m/s^2)",
    "current": "A",
    "pressure": "bar",
    "temperature": "degC",
    "thermocouple": "degC",
    "voltage": "V",
    "volume_flow_rate_rms": "m^3/h",
}

DESCRIPTIONS = {
    "datetime": "Sample timestamp of the SCADA system (1 Hz)",
    "accelerometer1_rms": "RMS vibration, accelerometer 1 (pump body / valve)",
    "accelerometer2_rms": "RMS vibration, accelerometer 2 (remote bearing)",
    "current": "Current drawn by the circulation pump",
    "pressure": "Fluid pressure in the pipeline",
    "temperature": "Temperature of the circulating fluid",
    "thermocouple": "Temperature at the valve transmission thermocouple",
    "voltage": "Supply voltage of the electrical circuit",
    "volume_flow_rate_rms": "RMS volumetric flow rate of the circulation loop",
    "anomaly": "Target label - 1 = physical anomaly, 0 = normal",
    "changepoint": "Change-point label - 1 = regime change, 0 = stable",
    "run": "Run identifier (source file number, 0-15)",
}


def to_snake_case(name: str) -> str:
    """'Volume Flow RateRMS' -> 'volume_flow_rate_rms'."""
    name = re.sub(r"[^0-9a-zA-Z]+", "_", name.strip())
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    name = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    return re.sub(r"_+", "_", name).strip("_").lower()


def run_sort_key(path: str) -> int:
    """Sort helper so run 2 comes before run 10."""
    return int(re.search(r"(\d+)", os.path.basename(path)).group(1))


def clean_frame(df: pd.DataFrame, decimals: int) -> pd.DataFrame:
    """Normalise dtypes, rounding and timestamp format of a single run."""
    df = df.copy()
    df.columns = [to_snake_case(c) for c in df.columns]

    if "datetime" in df.columns:
        df["datetime"] = pd.to_datetime(
            df["datetime"], format="%Y-%m-%d %H:%M:%S", errors="raise"
        ).dt.strftime("%Y-%m-%d %H:%M:%S")

    for col in FLAG_COLUMNS:
        if col in df.columns:
            df[col] = df[col].round().astype("int64")

    for col in df.columns:
        if col == "datetime" or col in FLAG_COLUMNS:
            continue
        df[col] = df[col].astype("float64").round(decimals)

    return df


def write_readme(out_dir: str, columns: list, decimals: int) -> None:
    lines = [
        "# SKAB Valve1 - reformatted data",
        "",
        "Generated by `scripts/prepare_skab.py` from `data/raw/skab/valve1/`.",
        "Do not edit by hand - re-run the script instead.",
        "",
        "## Files",
        "",
        "| File | Description |",
        "| --- | --- |",
        "| `run_00.csv` ... `run_15.csv` | One file per test run, rows in original order |",
        "| `all_runs.csv` | All 16 runs stacked, extra `run` column identifies the source |",
        "| `run_index.csv` | Per-run summary (row counts, label counts, time span) |",
        "",
        "## Format",
        "",
        "- Comma-delimited, UTF-8, LF line endings, one header row",
        f"- Sensor values rounded to {decimals} decimals",
        "- `anomaly` and `changepoint` are integer flags (0 / 1)",
        "- Timestamps in `YYYY-MM-DD HH:MM:SS`, one second apart within a run",
        "",
        "## Columns",
        "",
        "| Column | Unit | Description |",
        "| --- | --- | --- |",
    ]
    for col in columns:
        unit = UNITS.get(col, "-")
        desc = DESCRIPTIONS.get(col, "")
        lines.append(f"| `{col}` | {unit} | {desc} |")

    with open(os.path.join(out_dir, "README.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw_dir", default=DEFAULT_RAW_DIR, help="Directory with raw SKAB CSVs")
    parser.add_argument("--out_dir", default=DEFAULT_OUT_DIR, help="Output directory")
    parser.add_argument("--decimals", type=int, default=4, help="Decimal places for sensor values")
    args = parser.parse_args()

    raw_dir, out_dir = args.raw_dir, args.out_dir
    if not os.path.isdir(raw_dir):
        print(f"ERROR: raw directory not found: {raw_dir}", file=sys.stderr)
        return 1

    raw_files = sorted(
        [f for f in os.listdir(raw_dir) if f.lower().endswith(".csv")],
        key=lambda n: run_sort_key(os.path.join(raw_dir, n)),
    )
    if not raw_files:
        print(f"ERROR: no CSV files found in {raw_dir}", file=sys.stderr)
        return 1

    os.makedirs(out_dir, exist_ok=True)

    frames, index_rows, columns = [], [], None
    for fname in raw_files:
        run_id = run_sort_key(os.path.join(raw_dir, fname))
        df = clean_frame(pd.read_csv(os.path.join(raw_dir, fname), sep=";"), args.decimals)
        if columns is None:
            columns = list(df.columns)

        out_name = f"run_{run_id:02d}.csv"
        df.to_csv(os.path.join(out_dir, out_name), index=False, lineterminator="\n")

        df.insert(0, "run", run_id)
        frames.append(df)

        index_rows.append({
            "run": run_id,
            "source_file": fname,
            "rows": len(df),
            "start": df["datetime"].iloc[0] if "datetime" in df.columns else "",
            "end": df["datetime"].iloc[-1] if "datetime" in df.columns else "",
            "anomalies": int(df["anomaly"].sum()) if "anomaly" in df.columns else 0,
            "changepoints": int(df["changepoint"].sum()) if "changepoint" in df.columns else 0,
        })

    all_runs = pd.concat(frames, ignore_index=True)
    all_runs.to_csv(os.path.join(out_dir, "all_runs.csv"), index=False, lineterminator="\n")
    pd.DataFrame(index_rows).to_csv(os.path.join(out_dir, "run_index.csv"), index=False, lineterminator="\n")
    write_readme(out_dir, columns, args.decimals)

    total = len(all_runs)
    print(f"Reformatted {len(raw_files)} runs -> {out_dir}")
    print(f"  run_XX.csv    : {len(raw_files)} files, {sum(r['rows'] for r in index_rows)} rows total")
    print(f"  all_runs.csv  : {total} rows, {len(all_runs.columns)} columns")
    print(f"  run_index.csv : per-run summary")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
